#!/usr/bin/env node
/**
 * gen-timeline-metrics.mjs — measure Figtree's per-character advances and write
 * src/engine/timeline-metrics.ts, the static table timelineTextWidth (src/engine/timeline-text.ts)
 * sums to measure timeline text.
 *
 * It loads the font the engine embeds (src/embed/assets/Figtree-variable.ttf) into headless
 * Chromium as a FontFace and reads each character's advance with canvas measureText at 1000px,
 * at the two weights a timeline draws (500 and 700), so the table is in thousandths of an em.
 * One character at a time: kerning is never measured, and timelineTextWidth ignores it.
 *
 * Run by hand after changing the font or the character set: node scripts/gen-timeline-metrics.mjs
 * (needs playwright's Chromium: npx playwright install chromium). It is not part of the build or
 * the tests — the engine only ever reads the committed table.
 */

import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FONT_PATH = resolve(ROOT, "src/embed/assets/Figtree-variable.ttf");
const OUT_PATH = resolve(ROOT, "src/engine/timeline-metrics.ts");
const WEIGHTS = [500, 700];

// Printable ASCII, Latin-1 (NBSP, "·" and the accented letters of names and places), and the
// punctuation timeline text emits (the en dash of a range) or commonly contains.
const chars = [];
for (let c = 32; c <= 126; c++) chars.push(String.fromCharCode(c));
for (let c = 0xa0; c <= 0xff; c++) chars.push(String.fromCharCode(c));
chars.push("–", "—", "‘", "’", "“", "”", "…", "•");

const fontB64 = (await readFile(FONT_PATH)).toString("base64");
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const table = await page.evaluate(async ({ fontB64, chars, weights }) => {
    const bytes = Uint8Array.from(atob(fontB64), (c) => c.charCodeAt(0));
    const face = new FontFace("FigtreeMetrics", bytes, { weight: "300 900" });
    await face.load();
    document.fonts.add(face);
    const ctx = document.createElement("canvas").getContext("2d");
    const out = {};
    for (const w of weights) {
      ctx.font = `${w} 1000px FigtreeMetrics`;
      out[w] = chars.map((ch) => ctx.measureText(ch).width);
    }
    // Sanity: a weight the face does not cover would fall back to another font silently.
    ctx.font = "500 1000px FigtreeMetrics";
    const own = ctx.measureText("Figtree").width;
    ctx.font = "500 1000px monospace";
    if (Math.abs(ctx.measureText("Figtree").width - own) < 1) throw new Error("font did not load");
    return out;
  }, { fontB64, chars, weights: WEIGHTS });

  const round = (x) => Math.round(x * 10) / 10;
  // The fallback for a character outside the table is the mean advance of the ASCII letters and
  // digits at that weight: an unknown character is most likely a letter of another alphabet, and
  // that mean sits between the narrow and wide letters where a fixed 0.55em would not track weight.
  const alnum = chars.map((c, i) => [c, i]).filter(([c]) => /[A-Za-z0-9]/.test(c)).map(([, i]) => i);
  const fallback = Object.fromEntries(
    WEIGHTS.map((w) => [w, round(alnum.reduce((s, i) => s + table[w][i], 0) / alnum.length)]),
  );
  const esc = (s) => JSON.stringify(s);
  const lines = [
    "// GENERATED by scripts/gen-timeline-metrics.mjs from src/embed/assets/Figtree-variable.ttf — do not",
    "// edit by hand. Regenerate: node scripts/gen-timeline-metrics.mjs (needs playwright's Chromium).",
    "// Figtree advance widths, in thousandths of an em, at the weights a timeline draws. Kerning is not",
    "// in the table (each character is measured alone).",
    "",
    "/** The characters the table covers, in the order of each weight's advances. */",
    `export const FIGTREE_CHARS = ${esc(chars.join(""))};`,
    "",
    "/** Advance per character of FIGTREE_CHARS, per 1000 em, by font weight. */",
    "export const FIGTREE_ADVANCE: Record<500 | 700, readonly number[]> = {",
    ...WEIGHTS.map((w) => `  ${w}: [${table[w].map(round).join(", ")}],`),
    "};",
    "",
    "/** Advance for a character outside the table, per 1000 em: the mean of the ASCII letters and",
    " *  digits at that weight. */",
    `export const FIGTREE_FALLBACK: Record<500 | 700, number> = { 500: ${fallback[500]}, 700: ${fallback[700]} };`,
    "",
  ];
  await writeFile(OUT_PATH, lines.join("\n"), "utf8");
  console.log(`wrote ${OUT_PATH}: ${chars.length} characters; fallback 500=${fallback[500]} 700=${fallback[700]}`);
} finally {
  await browser.close();
}
