#!/usr/bin/env node
/**
 * gen-grapheme-data.mjs — write src/engine/grapheme-data.ts, the static Unicode property ranges the
 * engine's built-in grapheme splitter (`graphemes` in src/engine/timeline-text.ts) reads.
 *
 * The splitter does not use Intl.Segmenter or regex property escapes at run time: both answer from
 * the runtime's own Unicode version, so a hard break could fall at a different point in Node (the
 * jsdom goldens) and in a reader's browser. These tables are frozen at the Unicode version of the
 * Node that runs this script, so every runtime splits identically.
 *
 * Run by hand to move to a newer Unicode version: node scripts/gen-grapheme-data.mjs. It is not
 * part of the build or the tests — the engine only ever reads the committed file.
 */

import { writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const OUT_PATH = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src/engine/grapheme-data.ts");

/** Inclusive [start, end] runs of the code points `test` accepts, flattened. */
function ranges(test) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp <= 0x10ffff && test(cp);
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push(start, cp - 1);
      start = -1;
    }
  }
  return out;
}

// UAX #29 Extend (Grapheme_Extend, Emoji_Modifier) and SpacingMark (approximated as Mc, plus the
// two Lo vowels Thai SARA AM and Lao AM that the standard lists).
const MARKS = /^[\p{Grapheme_Extend}\p{Emoji_Modifier}\p{Mc}]$/u;
const extend = ranges((cp) => MARKS.test(String.fromCodePoint(cp)) || cp === 0x0e33 || cp === 0x0eb3);
const pictographic = ranges((cp) => /^\p{Extended_Pictographic}$/u.test(String.fromCodePoint(cp)));
/** The pairs as source, ten to a line. */
const hex = (a) => {
  const rows = [];
  for (let i = 0; i < a.length; i += 10) rows.push(`  ${a.slice(i, i + 10).map((n) => `0x${n.toString(16)}`).join(", ")},`);
  return ["", ...rows, ""].join(String.fromCharCode(10));
};

const lines = [
  "// GENERATED by scripts/gen-grapheme-data.mjs — do not edit by hand. Regenerate: node",
  "// scripts/gen-grapheme-data.mjs.",
  `// Unicode ${process.versions.unicode}, frozen so that every runtime splits graphemes identically.`,
  "",
  "/** Code points that never start a grapheme (UAX #29 Extend and SpacingMark: combining marks,",
  " *  variation selectors, emoji skin-tone modifiers, tag characters, the keycap mark), as flattened",
  " *  inclusive [start, end] pairs in ascending order. */",
  `export const GRAPHEME_EXTEND: readonly number[] = [${hex(extend)}];`,
  "",
  "/** Extended_Pictographic code points (the emoji a ZWJ joins), as flattened inclusive [start, end]",
  " *  pairs in ascending order. */",
  `export const EXTENDED_PICTOGRAPHIC: readonly number[] = [${hex(pictographic)}];`,
  "",
];
await writeFile(OUT_PATH, lines.join("\n"), "utf8");
console.log(`wrote ${OUT_PATH}: Unicode ${process.versions.unicode}, ${extend.length / 2} extend and ${pictographic.length / 2} pictographic ranges`);
